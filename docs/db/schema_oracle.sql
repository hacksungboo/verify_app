-- Verifi 스키마 (Oracle 23ai). 앱이 기동 시 자동 생성하므로 직접 실행할 필요는 없어요.
-- 생성: SQLAlchemy 모델(backend/app/models.py)에서 oracle 방언으로 컴파일

CREATE TABLE vf_users (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY, 
	email VARCHAR2(200 CHAR) NOT NULL, 
	display_name VARCHAR2(100 CHAR) NOT NULL, 
	password_hash VARCHAR2(300 CHAR) NOT NULL, 
	created_at DATE NOT NULL, 
	PRIMARY KEY (id), 
	UNIQUE (email)
);

CREATE TABLE vf_reviews (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY, 
	title VARCHAR2(300 CHAR) NOT NULL, 
	sample_id VARCHAR2(100 CHAR), 
	owner_id INTEGER NOT NULL, 
	status VARCHAR2(20 CHAR) NOT NULL, 
	stage VARCHAR2(100 CHAR) NOT NULL, 
	total_claims INTEGER NOT NULL, 
	processed_claims INTEGER NOT NULL, 
	provider VARCHAR2(50 CHAR) NOT NULL, 
	error_message VARCHAR2(1000 CHAR), 
	created_at DATE NOT NULL, 
	finished_at DATE, 
	completed_at DATE, 
	PRIMARY KEY (id), 
	FOREIGN KEY(owner_id) REFERENCES vf_users (id)
);

CREATE TABLE vf_claims (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY, 
	review_id INTEGER NOT NULL, 
	seq INTEGER NOT NULL, 
	content VARCHAR2(2000 CHAR) NOT NULL, 
	span_start INTEGER NOT NULL, 
	span_end INTEGER NOT NULL, 
	claim_type VARCHAR2(20 CHAR) NOT NULL, 
	verdict VARCHAR2(20 CHAR) NOT NULL, 
	confidence FLOAT NOT NULL, 
	risk FLOAT NOT NULL, 
	evidence_chunk_id INTEGER, 
	quote VARCHAR2(2000 CHAR), 
	explanation VARCHAR2(1000 CHAR), 
	suggestion VARCHAR2(2000 CHAR), 
	evidence_json CLOB NOT NULL, 
	decision VARCHAR2(20 CHAR) NOT NULL, 
	edited_text VARCHAR2(2000 CHAR), 
	decided_at DATE, 
	PRIMARY KEY (id), 
	FOREIGN KEY(review_id) REFERENCES vf_reviews (id)
);

CREATE TABLE vf_documents (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY, 
	review_id INTEGER NOT NULL, 
	doc_kind VARCHAR2(10 CHAR) NOT NULL, 
	title VARCHAR2(300 CHAR) NOT NULL, 
	content CLOB NOT NULL, 
	created_at DATE NOT NULL, 
	PRIMARY KEY (id), 
	FOREIGN KEY(review_id) REFERENCES vf_reviews (id)
);

CREATE TABLE vf_review_sessions (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY, 
	review_id INTEGER, 
	session_kind VARCHAR2(20 CHAR) NOT NULL, 
	reviewer VARCHAR2(100 CHAR) NOT NULL, 
	duration_sec INTEGER NOT NULL, 
	planted_errors INTEGER NOT NULL, 
	found_errors INTEGER NOT NULL, 
	false_positives INTEGER NOT NULL, 
	is_sample INTEGER NOT NULL, 
	note VARCHAR2(500 CHAR), 
	created_at DATE NOT NULL, 
	PRIMARY KEY (id), 
	FOREIGN KEY(review_id) REFERENCES vf_reviews (id)
);

CREATE TABLE vf_chunks (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY, 
	document_id INTEGER NOT NULL, 
	seq INTEGER NOT NULL, 
	content VARCHAR2(4000 CHAR) NOT NULL, 
	char_start INTEGER NOT NULL, 
	char_end INTEGER NOT NULL, 
	PRIMARY KEY (id), 
	FOREIGN KEY(document_id) REFERENCES vf_documents (id)
);

